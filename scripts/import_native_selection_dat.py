#!/usr/bin/env python3
"""Add native selection DAT metadata to a new copy of Joey's SQLite.

Consumes selection-manifests.json generated by summarize_native_selection_dat.py.
No sprites, binaries or complete proprietary manifests are stored.
"""
from __future__ import annotations
import argparse
import json
import sqlite3
from contextlib import closing
from pathlib import Path

SHA = "db8fe7b7ea4b12f18a9bb1777b5f5b8eab254011db2a52571a0264725505b6de"
PREFIXES = ("j\\duel\\list\\", "j\\duel\\list_icon\\")
REQUIRED = {f"j\\duel\\list\\{family}{side}.txt"
            for family in ("selectlist", "gravelist", "fusionlist", "excludelist")
            for side in (1, 2)}
ORIGIN = "summarize_native_selection_dat.py / original data.dat metadata"


def canonical_path(name):
    if not isinstance(name, str):
        raise ValueError("Invalid resource path")
    name = name.replace("/", "\\").lower()
    if ".." in name.split("\\") or not name.startswith(PREFIXES):
        raise ValueError(f"Out-of-scope resource path: {name}")
    return name


def manifest_rows(text):
    if not isinstance(text, str):
        raise ValueError("Manifest is missing Latin1 content")
    rows = []
    for number, line in enumerate(text.splitlines(), 1):
        line = line.split("//", 1)[0].strip()
        if not line:
            continue
        parts = line.split()
        if len(parts) not in (1, 2) or not parts[0].lower().endswith((".txt", ".bmp", ".yga")):
            raise ValueError(f"Bad manifest entry at line {number}")
        raw = parts[1] if len(parts) == 2 else None
        if raw is not None and (not raw.isascii() or not raw.isdecimal()):
            raise ValueError(f"Bad numeric value at line {number}")
        rows.append((number, parts[0], raw, int(raw) if raw is not None else None))
    return rows


def unpack_scroll(number):
    """Four original fields assigned in decompiled FUN_0043BA30."""
    if not 0 <= number <= 0x7FFFFFFF:
        raise ValueError("Scroll number outside signed DWORD")
    return (number // 10000000, (number // 100000) % 100,
            (number // 1000) % 100, number % 1000)


def collect(data):
    if data.get("schemaVersion") != 1 or not isinstance(data.get("manifests"), list) or not isinstance(data.get("images"), list):
        raise ValueError("Unexpected selection-manifests.json format")
    manifests, images, entries, scrolls = [], [], [], []
    manifest_names, image_names = set(), set()
    for record in data["manifests"]:
        path = canonical_path(record["name"])
        if path in manifest_names or not path.endswith(".txt"):
            raise ValueError("Duplicate or invalid manifest " + path)
        manifest_names.add(path)
        lines = manifest_rows(record["latin1"])
        if not lines:
            raise ValueError("Empty manifest " + path)
        manifests.append((path, len(lines), ORIGIN))
        for i, (line_number, filename, raw, numeric) in enumerate(lines):
            if "\\" in filename or "/" in filename or filename in (".", ".."):
                raise ValueError("Invalid relative resource reference")
            target = canonical_path(path.rsplit("\\", 1)[0] + "\\" + filename)
            entries.append((path, i, line_number, target, raw, numeric))
        if "_scroll" in path:
            numeric = lines[0][3]
            if numeric is None:
                raise ValueError("Missing packed scroll number " + path)
            scrolls.append((path, numeric, *unpack_scroll(numeric), "0043BA30"))
    if not REQUIRED.issubset(manifest_names):
        raise ValueError("Missing required manifests: " + str(sorted(REQUIRED - manifest_names)))
    for record in data["images"]:
        path = canonical_path(record["name"])
        if path in image_names or not path.endswith((".bmp", ".yga")):
            raise ValueError("Duplicate or invalid image " + path)
        image_names.add(path)
        width, height = record.get("width"), record.get("height")
        if type(width) is not int or type(height) is not int or width <= 0 or height <= 0 or record.get("error") is not None:
            raise ValueError("Unusable image metadata: " + path)
        images.append((path, width, height, record.get("decodedBytes"), ORIGIN))
    missing = sorted({entry[3] for entry in entries if entry[3] not in manifest_names and entry[3] not in image_names})
    if missing:
        raise ValueError("Missing resource references: " + str(missing))
    return manifests, images, entries, scrolls


def enrich(source, destination, data, summary=None):
    source, destination = Path(source).resolve(), Path(destination).resolve()
    if not source.is_file() or source == destination or destination.exists():
        raise ValueError("Input must exist and output must be a NEW file")
    manifests, images, entries, scrolls = collect(data)
    destination.parent.mkdir(parents=True, exist_ok=True)
    try:
        with closing(sqlite3.connect(source.as_uri() + "?mode=ro", uri=True)) as old:
            sha = old.execute("SELECT value FROM metadata WHERE key='executable_sha256'").fetchone()
            if not sha or sha[0].lower() != SHA:
                raise ValueError("Source SQLite executable SHA mismatch")
            with closing(sqlite3.connect(destination)) as db:
                old.backup(db)
                with db:
                    db.executescript("""
                    CREATE TABLE visual_dat_manifests (
                        path TEXT PRIMARY KEY, entry_count INTEGER NOT NULL, evidence_source TEXT NOT NULL);
                    CREATE TABLE visual_dat_images (
                        path TEXT PRIMARY KEY, width INTEGER NOT NULL, height INTEGER NOT NULL,
                        decoded_bytes INTEGER, evidence_source TEXT NOT NULL);
                    CREATE TABLE visual_dat_entries (
                        manifest_path TEXT NOT NULL, entry_index INTEGER NOT NULL,
                        source_line INTEGER NOT NULL, resource_path TEXT NOT NULL,
                        numeric_raw TEXT, numeric_value INTEGER,
                        PRIMARY KEY(manifest_path,entry_index));
                    CREATE TABLE visual_dat_scroll_fields (
                        manifest_path TEXT PRIMARY KEY, packed_integer INTEGER NOT NULL,
                        part_0 INTEGER NOT NULL, part_1 INTEGER NOT NULL,
                        part_2 INTEGER NOT NULL, part_3 INTEGER NOT NULL,
                        decoder_function TEXT NOT NULL);
                    CREATE VIEW visual_dat_entry_details AS
                        SELECT e.manifest_path,e.entry_index,e.resource_path,
                               e.numeric_raw,e.numeric_value,i.width,i.height
                        FROM visual_dat_entries e LEFT JOIN visual_dat_images i
                        ON e.resource_path=i.path;
                    """)
                    db.executemany("INSERT INTO visual_dat_manifests VALUES (?,?,?)", manifests)
                    db.executemany("INSERT INTO visual_dat_images VALUES (?,?,?,?,?)", images)
                    db.executemany("INSERT INTO visual_dat_entries VALUES (?,?,?,?,?,?)", entries)
                    db.executemany("INSERT INTO visual_dat_scroll_fields VALUES (?,?,?,?,?,?,?)", scrolls)
                if db.execute("PRAGMA integrity_check").fetchone()[0] != "ok":
                    raise ValueError("SQLite integrity check failed")
        report = {"executableSha256": SHA, "manifests": len(manifests), "images": len(images),
                  "manifestEntries": len(entries), "scrollDescriptors": len(scrolls),
                  "unresolvedResourceReferences": 0,
                  "note": "Packed scroll fields decoded per 0043BA30; roles unknown."}
        if summary is not None:
            target = Path(summary)
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
        return report
    except Exception:
        destination.unlink(missing_ok=True)
        raise


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--source", type=Path, required=True)
    p.add_argument("--dat-selection", type=Path, required=True)
    p.add_argument("--output", type=Path, required=True)
    p.add_argument("--summary", type=Path)
    args = p.parse_args()
    try:
        data = json.loads(args.dat_selection.read_text(encoding="utf-8"))
        print(json.dumps(enrich(args.source, args.output, data, args.summary)))
    except (OSError, ValueError, TypeError, sqlite3.Error) as err:
        p.error(str(err))


if __name__ == "__main__":
    main()
