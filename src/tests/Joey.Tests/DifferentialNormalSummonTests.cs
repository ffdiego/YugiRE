using Joey.Core;
using System.Text.Json;
using System.Text.Json.Nodes;

// DIFFERENTIAL PILOT, NOT FULL NATIVE REPLAY.
// Inputs and expected outputs were transcribed from two operator-observed
// Joey sessions. Only the projected fields are checked against the native
// observations; unknown hand metadata, flags, deck, graveyard and animation
// state are deliberately not claimed as matching.
internal static class DifferentialNormalSummonTests
{
    private sealed record PartialOutcome(
        int Side, int[] HandIndices, int?[] MonsterSlots,
        int LifePoints, bool ActionAccepted);

    private static int[] CardIndices(JsonElement values) =>
        values.EnumerateArray().Select(value => value.GetInt32()).ToArray();

    // Unknown cards are *surrogates*, not entries from the original CARD_ID
    // catalog. Their identity is only the observed internal index.
    // The selected monster uses an eligible ordinary level-four surrogate,
    // based on original preflight for 221, or explicitly an assumption for 705.
    private static Card Surrogate(int index, bool selected, ushort resourceId)
    {
        uint properties = selected ? ((1u << 20) | (4u << 25)) : 0;
        return new Card(index, resourceId,
            "Observation-only internal card " + index, "", properties);
    }

    private static Card?[] KnownMonsters(JsonElement known, string key)
    {
        Card?[] result = new Card?[5];
        if (!known.TryGetProperty(key, out JsonElement source) ||
            source.ValueKind == JsonValueKind.Null)
            return result;
        if (source.ValueKind != JsonValueKind.Array ||
            source.GetArrayLength() != 5)
            throw new InvalidDataException(key + " must have five slots");
        int slot = 0;
        foreach (JsonElement element in source.EnumerateArray())
        {
            if (element.ValueKind != JsonValueKind.Null)
                result[slot] = Surrogate(element.GetInt32(), false, ushort.MaxValue);
            slot++;
        }
        return result;
    }

    private static PartialOutcome Project(DemoDuel duel, bool accepted) =>
        new(duel.ActivePlayer,
            duel.Hand.Select(card => card.Index).ToArray(),
            Enumerable.Range(0, 5).Select(slot =>
                (int?)duel.Monsters[duel.ActivePlayer, slot]?.Index).ToArray(),
            duel.Life[duel.ActivePlayer],
            accepted);

    private static (PartialOutcome Before, PartialOutcome After, JsonElement Expected, bool HasLp) Replay(
        string file)
    {
        using JsonDocument document = JsonDocument.Parse(File.ReadAllText(file));
        JsonElement root = document.RootElement;
        if (root.GetProperty("schema").GetString() != "yugire.partial-normal-summon.v1")
            throw new InvalidDataException("Unsupported native observation fixture");
        if (root.GetProperty("limitations").GetArrayLength() == 0 ||
            string.IsNullOrWhiteSpace(root.GetProperty("source").GetString()))
            throw new InvalidDataException("Fixture must name original evidence and limitations");

        JsonElement input = root.GetProperty("before");
        JsonElement action = root.GetProperty("action");
        JsonElement expected = root.GetProperty("after");
        int side = input.GetProperty("activeSide").GetInt32();
        int handIndex = action.GetProperty("handIndex").GetInt32();
        int zone = action.GetProperty("fieldSlot").GetInt32();
        int selected = action.GetProperty("sourceCardIndex").GetInt32();
        int[] initialHand = CardIndices(input.GetProperty("activeHandIndices"));
        if (action.GetProperty("kind").GetString() != "normalSummon" ||
            action.GetProperty("side").GetInt32() != side ||
            handIndex < 0 || handIndex >= initialHand.Length ||
            initialHand[handIndex] != selected)
            throw new InvalidDataException("The native action does not match its observed input hand");

        // An optional CE descriptor is an independent ORIGINAL evidence
        // consistency check, not output generated by the demo engine.
        if (action.TryGetProperty("ceContext", out JsonElement contextElement))
        {
            uint context = contextElement.GetUInt32();
            if ((context & 1) != side ||
                ((context >> 6) & 0xFF) != handIndex ||
                ((context >> 1) & 0x1F) != zone)
                throw new InvalidDataException("Native CE context contradicts selected side/hand/slot");
        }

        ushort resourceId = action.TryGetProperty("resourceId", out JsonElement resource)
            ? resource.GetUInt16() : ushort.MaxValue;
        List<Card> cards = initialHand.Select((idx, i) =>
            Surrogate(idx, i == handIndex, i == handIndex ? resourceId : ushort.MaxValue)).ToList();
        Card?[] activeZones = KnownMonsters(input, "knownActiveMonsters");
        Card?[] opponentZones = KnownMonsters(input, "knownOpponentMonsters");
        bool hasLp = input.TryGetProperty("activeLifePoints", out JsonElement observedLp) &&
                     observedLp.ValueKind == JsonValueKind.Number;
        int life = hasLp ? observedLp.GetInt32() : 8000; // unobserved default; excluded from parity

        DemoDuel duel = DemoDuel.FromPartialObservation(
            side, cards,
            side == 0 ? activeZones : opponentZones,
            side == 1 ? activeZones : opponentZones, life);

        PartialOutcome before = Project(duel, false);
        if (before.Side != side || !before.HandIndices.SequenceEqual(initialHand) ||
            !before.MonsterSlots.SequenceEqual(activeZones.Select(c => (int?)c?.Index)))
            throw new InvalidDataException("Demo initial projection does not match native-known fields");
        if (activeZones[zone] is not null)
            throw new InvalidDataException("First pilot supports placement into an empty destination");
        bool accepted = duel.Summon(handIndex, side, zone, true, out _);
        return (before, Project(duel, accepted), expected.Clone(), hasLp);
    }

    private static bool SameObservedFields(PartialOutcome result, JsonElement expected, bool hasLp)
    {
        int slot = expected.GetProperty("fieldSlot").GetInt32();
        int target = expected.GetProperty("cardIndex").GetInt32();
        bool hand = result.HandIndices.Length == expected.GetProperty("activeHandCount").GetInt32();
        bool monster = slot is >= 0 and < 5 && result.MonsterSlots[slot] == target;
        bool life = !hasLp || result.LifePoints == expected.GetProperty("activeLifePoints").GetInt32();
        return result.ActionAccepted && hand && monster && life;
    }

    public static void Run(Action<bool, string> check)
    {
        foreach (string name in new[]
        {
            "console-normal-summon-side1-221",
            "watch-normal-summon-side1-705-slot1"
        })
        {
            string path = Path.Combine(AppContext.BaseDirectory, "Fixtures", name + ".json");
            var (before, after, expected, hasLp) = Replay(path);
            check(before.HandIndices.Length == after.HandIndices.Length + 1,
                name + ": hand lost exactly one card in DemoDuel");
            check(SameObservedFields(after, expected, hasLp),
                name + ": native-observed hand count and placed index/slot agree with DemoDuel");

            // Negative control: the parity predicate MUST reject a different
            // native-observed card/slot, rather than always reporting success.
            int wrongCard = expected.GetProperty("cardIndex").GetInt32() + 1;
            JsonObject bad = JsonNode.Parse(expected.GetRawText())!.AsObject();
            bad["cardIndex"] = wrongCard;
            using JsonDocument perturbed = JsonDocument.Parse(bad.ToJsonString());
            check(!SameObservedFields(after, perturbed.RootElement, hasLp),
                name + ": differential comparator rejects a mutated expected card");
        }
    }
}
